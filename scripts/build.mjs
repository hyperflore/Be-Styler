import fs from "node:fs";
import path from "node:path";
import vm from "node:vm";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const SRC = path.join(ROOT, "src");
const THEMES = path.join(ROOT, "themes");
let DIST = path.join(ROOT, "dist");

const args = process.argv.slice(2);
const WATCH = args.includes("--watch");
const CHECK_ONLY = args.includes("--check");

const THEME_PLUGINS = ["cursorPet.js", "sakuraPetals.js", "screenEffects.js", "cssTweaks.js", "macmize.js", "usernameTools.js", "compactServers.js", "loadingQuotes.js"];
const VARIANTS = {
    styler: { out: "dist", keepPlugin: f => THEME_PLUGINS.includes(f), themes: true, features: { meow: false, owlie: false } },
};
const variantArg = (args.find(a => a.startsWith("--variant=")) || "--variant=styler").slice("--variant=".length);
const VARIANT = VARIANTS[variantArg];
if (!VARIANT) {
    console.error(`Unknown --variant=${variantArg}. Use one of: ${Object.keys(VARIANTS).join(", ")}`);
    process.exit(1);
}
const outArg = args.find(a => a.startsWith("--out="));
DIST = outArg ? path.resolve(ROOT, outArg.slice("--out=".length)) : path.join(ROOT, VARIANT.out);

const c = { pink: s => `\x1b[95m${s}\x1b[0m`, green: s => `\x1b[32m${s}\x1b[0m`, red: s => `\x1b[31m${s}\x1b[0m`, dim: s => `\x1b[2m${s}\x1b[0m` };
const rel = p => path.relative(ROOT, p).replaceAll("\\", "/");

class BuildError extends Error {}

const read = file => fs.readFileSync(file, "utf8");

function check(code, filename) {
    try {
        new vm.Script(code, { filename });
    } catch (e) {
        const where = e.stack?.split("\n")[0] || filename;
        throw new BuildError(`${where}\n  ${e.message}`);
    }
}

function write(file, data) {
    fs.mkdirSync(path.dirname(file), { recursive: true });
    const tmp = `${file}.tmp`;
    fs.writeFileSync(tmp, data);
    fs.renameSync(tmp, file);
}

function listPlugins() {
    const dir = path.join(SRC, "plugins");
    if (!fs.existsSync(dir)) return [];
    return fs.readdirSync(dir)
        .filter(f => f.endsWith(".js") && !f.startsWith("_"))
        .sort()
        .map(f => path.join(dir, f));
}

function pluginIds(source) {
    return [...source.matchAll(/definePlugin\(\s*\{[\s\S]*?\bid\s*:\s*["'`]([^"'`]+)["'`]/g)].map(m => m[1]);
}

function build() {
    const started = Date.now();
    const pkg = JSON.parse(read(path.join(ROOT, "package.json")));
    const banner = name => `/* Be Themer v${pkg.version} · ${name} · generated by scripts/build.mjs, edit src/ instead */\n`;

    const cjs = code => `(function (exports, require, module, __filename, __dirname) {\n${code}\n})`;
    const main = read(path.join(SRC, "main", "index.js"));
    const preload = read(path.join(SRC, "preload", "index.js"));
    const shim = read(path.join(SRC, "shared", "shim.js"));
    check(cjs(main), rel(path.join(SRC, "main", "index.js")));
    check(cjs(preload), rel(path.join(SRC, "preload", "index.js")));
    check(cjs(shim), rel(path.join(SRC, "shared", "shim.js")));

    const repoUrl = () => {
        const raw = typeof pkg.repository === "string" ? pkg.repository : pkg.repository?.url || "";
        const m = /github\.com[/:]([\w.-]+\/[\w.-]+?)(?:\.git)?\/?$/i.exec(raw) || /^([\w.-]+\/[\w.-]+)$/.exec(raw);
        return m ? `https://github.com/${m[1]}` : "";
    };

    const logoFile = path.join(ROOT, "assets", "logo-64.png");
    const logo = fs.existsSync(logoFile) ? `data:image/png;base64,${fs.readFileSync(logoFile).toString("base64")}` : "";
    const logoHdFile = path.join(ROOT, "assets", "logo-256.png");
    const logoHd = fs.existsSync(logoHdFile) ? `data:image/png;base64,${fs.readFileSync(logoHdFile).toString("base64")}` : "";
    const core = read(path.join(SRC, "renderer", "renderer.js"))
        .replace('"__BT_LOGO__"', () => JSON.stringify(logo))
        .replace('"__BT_LOGO_HD__"', () => JSON.stringify(logoHd))
        .replace('"__BT_REPO__"', () => JSON.stringify(repoUrl()))
        .replace("const FEATURES = __BT_FEATURES__;", () => `const FEATURES = ${JSON.stringify(VARIANT.features)};`);
    check(core, rel(path.join(SRC, "renderer", "renderer.js")));

    const plugins = listPlugins().filter(file => VARIANT.keepPlugin(path.basename(file)));
    const ids = new Map();
    const pluginChunks = plugins.map(file => {
        const name = path.basename(file);
        const source = read(file);
        check(`(function () {\n${source}\n})`, rel(file));
        for (const id of pluginIds(source)) {
            if (ids.has(id)) throw new BuildError(`Plugin id "${id}" is used by both ${ids.get(id)} and ${name}.`);
            ids.set(id, name);
        }
        return (
            `\n// built-in plugin: src/plugins/${name}\n` +
            `window.BThemer && window.BThemer.__withFile(${JSON.stringify(`builtin:${name}`)}, function () {\n${source}\n});\n`
        );
    });
    const renderer = banner("renderer") + core + "\n" + pluginChunks.join("");
    check(renderer, "dist/renderer.js");

    const themes = VARIANT.themes && fs.existsSync(THEMES) ? fs.readdirSync(THEMES).filter(f => f.endsWith(".css")) : [];

    if (CHECK_ONLY) {
        console.log(c.green("✔ check passed"), c.dim(`(${plugins.length} plugins, ${themes.length} themes)`));
        return;
    }

    write(path.join(DIST, "main.js"), banner("main") + main);
    write(path.join(DIST, "preload.js"), banner("preload") + preload);
    write(path.join(DIST, "shim.js"), banner("shim") + shim);
    write(path.join(DIST, "renderer.js"), renderer);
    for (const f of ["adblock.js", "adblock-preload.js"]) {
        const from = path.join(ROOT, "vendor", f);
        if (fs.existsSync(from)) write(path.join(DIST, f), fs.readFileSync(from));
    }

    fs.rmSync(path.join(DIST, "splash"), { recursive: true, force: true });

    const distThemes = path.join(DIST, "themes");
    fs.mkdirSync(distThemes, { recursive: true });
    for (const f of fs.readdirSync(distThemes)) if (!themes.includes(f)) fs.rmSync(path.join(distThemes, f), { force: true });
    for (const f of themes) {
        const src = read(path.join(THEMES, f));
        const dest = path.join(distThemes, f);
        if (!fs.existsSync(dest) || read(dest) !== src) write(dest, src);
    }

    write(path.join(DIST, "build-info.json"), JSON.stringify({
        version: pkg.version,
        builtAt: new Date().toISOString(),
        variant: variantArg,

        features: VARIANT.features,
        plugins: [...ids.keys()],
        themes,
    }, null, 2));

    const kb = f => `${(fs.statSync(path.join(DIST, f)).size / 1024).toFixed(1)} KB`;
    console.log(
        `${c.green("✔ built")} ${c.pink(`Be Themer v${pkg.version}`)} in ${Date.now() - started} ms ` +
        c.dim(`· renderer ${kb("renderer.js")} · ${ids.size} plugins (${[...ids.keys()].join(", ")}) · ${themes.length} theme(s)`)
    );
}

function safeBuild() {
    try {
        build();
        return true;
    } catch (e) {
        console.error(c.red(`✖ build failed: ${e instanceof BuildError ? e.message : e.stack || e}`));
        return false;
    }
}

const ok = safeBuild();

if (WATCH) {
    console.log(c.dim("watching src/ and themes/ … (Ctrl+C to stop)"));
    let timer;
    const rebuild = (_event, file) => {
        if (file && /\.tmp$/.test(file)) return;
        clearTimeout(timer);
        timer = setTimeout(safeBuild, 120);
    };
    for (const dir of [SRC, THEMES]) {
        try {
            fs.watch(dir, { recursive: true }, rebuild);
        } catch {
            fs.watch(dir, rebuild);
        }
    }
} else if (!ok) {
    process.exit(1);
}
