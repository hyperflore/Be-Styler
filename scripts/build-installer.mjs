import { execFileSync } from "node:child_process";
import crypto from "node:crypto";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const DIST = path.join(ROOT, "dist");
const INSTALLER = path.join(ROOT, "installer");
const RELEASE = path.join(ROOT, "release");

const c = { green: s => `\x1b[32m${s}\x1b[0m`, red: s => `\x1b[31m${s}\x1b[0m`, pink: s => `\x1b[95m${s}\x1b[0m`, dim: s => `\x1b[2m${s}\x1b[0m` };
const fail = msg => {
    console.error(c.red(`✖ ${msg}`));
    process.exit(1);
};

if (process.platform !== "win32") fail("The installer can only be built on Windows.");

execFileSync(process.execPath, [path.join(ROOT, "scripts", "build.mjs")], { stdio: "inherit" });

const windir = process.env.WINDIR || "C:\\Windows";
const csc = ["Framework64", "Framework"]
    .map(f => path.join(windir, "Microsoft.NET", f, "v4.0.30319", "csc.exe"))
    .find(f => fs.existsSync(f));
if (!csc) fail("Couldn't find csc.exe (.NET Framework 4). It ships with Windows 10/11; enable .NET Framework 4.8 in Windows Features.");

fs.mkdirSync(RELEASE, { recursive: true });
const iconPath = path.join(RELEASE, "b-themer.ico");
const logoIco = path.join(ROOT, "assets", "logo.ico");
if (fs.existsSync(logoIco)) fs.copyFileSync(logoIco, iconPath);
else fail("assets/logo.ico is missing. Run: node scripts/make-logo.mjs");

const walk = dir => fs.readdirSync(dir, { withFileTypes: true }).flatMap(e => (e.isDirectory() ? walk(path.join(dir, e.name)) : [path.join(dir, e.name)]));
const logoPng = path.join(ROOT, "assets", "logo-256.png");
function embeddedResources(dir) {
    const files = walk(dir).filter(f => !f.endsWith(".tmp"));
    const res = files.map(f => `/resource:${f},payload/${path.relative(dir, f).replaceAll("\\", "/")}`);
    if (fs.existsSync(logoPng)) res.push(`/resource:${logoPng},logo.png`);
    return { files, res };
}
const payload = embeddedResources(DIST).files;

const pkg = JSON.parse(fs.readFileSync(path.join(ROOT, "package.json"), "utf8"));
const repoField = typeof pkg.repository === "string" ? pkg.repository : pkg.repository?.url || "";
const repo = (/github(?:\.com[:/]|:)([\w.-]+\/[\w.-]+?)(?:\.git)?\/?$/.exec(repoField) || [])[1] || "";
let commit = "dev";
try {
    commit = execFileSync("git", ["rev-parse", "--short", "HEAD"], { cwd: ROOT, encoding: "utf8", stdio: ["ignore", "pipe", "ignore"] }).trim() || "dev";
} catch { }
const csString = s => JSON.stringify(String(s));
const configPath = path.join(RELEASE, "BuildConfig.g.cs");
fs.writeFileSync(configPath, `// generated by scripts/build-installer.mjs
namespace BThemer.Installer {
    public static class BuildConfig {
        public const string Version = ${csString(pkg.version)};
        public const string Commit = ${csString(commit)};
        public const string Repo = ${csString(repo)};
    }
}
`);

const sources = [...fs.readdirSync(INSTALLER).filter(f => f.endsWith(".cs")).map(f => path.join(INSTALLER, f)), configPath];
const refs = ["System.dll", "System.Core.dll", "System.Drawing.dll", "System.Windows.Forms.dll", "System.Web.Extensions.dll", "System.IO.Compression.dll", "System.IO.Compression.FileSystem.dll"].map(r => `/reference:${r}`);
const common = ["/nologo", "/optimize+", "/codepage:65001", "/utf8output", "/platform:anycpu", `/win32icon:${iconPath}`, `/win32manifest:${path.join(INSTALLER, "app.manifest")}`, ...refs];

function compile(out, extra, resources) {
    try {
        execFileSync(csc, [...common, ...extra, ...resources, `/out:${out}`, ...sources], { encoding: "utf8", stdio: ["ignore", "pipe", "pipe"] });
    } catch (e) {
        console.error(String(e.stdout || "") + String(e.stderr || ""));
        fail(`C# compile failed for ${path.basename(out)}`);
    }
}

for (const old of ["B-Themer-Installer.exe", "B-Themer-Installer-CLI.exe"]) {
    try {
        fs.rmSync(path.join(RELEASE, old), { force: true });
    } catch {
        console.log(c.dim(`  (couldn't remove old ${old}; it's open. Delete it after closing it.)`));
    }
}
function build(name, extra, resources) {
    const tmp = path.join(RELEASE, `${name}.build.tmp.exe`);
    fs.rmSync(tmp, { force: true });
    compile(tmp, extra, resources);
    const stamp = new Date().toTimeString().slice(0, 5).replace(":", "");
    const names = [`${name}.exe`, `${name}-${pkg.version}.exe`, `${name}-${pkg.version}-${stamp}.exe`];
    const locked = [];
    for (const file of names) {
        const target = path.join(RELEASE, file);
        try {
            fs.rmSync(target, { force: true });
            fs.renameSync(tmp, target);
            if (locked.length) {
                console.log(`\x1b[33m  ! ${locked.join(" and ")} ${locked.length > 1 ? "are" : "is"} open (in use), so NOT updated and now out of date.\n    The new build is ${file}. Run that one, or close the open installer and build again.\x1b[0m`);
            }
            return target;
        } catch {
            locked.push(file);
        }
    }
    fs.rmSync(tmp, { force: true });
    fail(`Couldn't save ${name}: ${locked.join(", ")} are all in use. Close the open installers and build again.`);
}
const gui = build("Be-Styler", ["/target:winexe"], embeddedResources(DIST).res);
const cli = build("Be-Styler-Cli", ["/target:exe", "/define:CLI"], embeddedResources(DIST).res);
fs.rmSync(iconPath, { force: true });
fs.rmSync(configPath, { force: true });

const zip = path.join(RELEASE, "dist.zip");
fs.rmSync(zip, { force: true });
execFileSync("powershell", ["-NoProfile", "-Command", `Compress-Archive -Path '${DIST}\\*' -DestinationPath '${zip}' -Force`], { stdio: "ignore" });

const sha = f => crypto.createHash("sha256").update(fs.readFileSync(f)).digest("hex");
const kb = f => `${(fs.statSync(f).size / 1024).toFixed(0)} KB`;
console.log(`${c.green("✔ installer built")} ${c.pink(`Be Themer v${pkg.version} (${commit})`)} ${c.dim(`· ${payload.length} files embedded · GitHub: ${repo || "not configured (set \"repository\" in package.json)"}`)}`);
const outputs = [gui, cli, zip];
for (const f of outputs) console.log(`  ${path.relative(ROOT, f)}  ${c.dim(`${kb(f)}  sha256 ${sha(f)}`)}`);
fs.writeFileSync(path.join(RELEASE, "SHA256SUMS.txt"), outputs.map(f => `${sha(f)}  ${path.basename(f)}`).join("\n") + "\n");
console.log(`  ${path.join("release", "SHA256SUMS.txt")}`);
